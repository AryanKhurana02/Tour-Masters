"""Load and serve 5-year historical weather climatology per destination with HCI.

CSV schema (generated by scripts/fetch_historical_weather.py):
  destination_id, destination_name, date, year, month, day_of_week,
  precipitation_mm, rain_mm, snowfall_cm, temp_max_c, temp_min_c,
  [cloud_cover_pct, wind_speed_kmh,] high_landslide_risk

The cloud-cover and wind-speed columns are required by the Holiday Climate
Index. Older CSV exports may omit them; when absent we fall back to neutral
mid-range values (50% cloud, 10 km/h wind) instead of failing, so the app
stays offline-safe.

Exports:
  get_monthly_climatology(destination_name: str, month: int) -> dict | None
  get_all_months_climatology(destination_name: str) -> list[dict] | None
  get_historical_weather_friction(destination_name: str, month: int) -> dict | None
"""

from __future__ import annotations

import csv
import logging
from pathlib import Path
from typing import Any

from app.services.crowd_score import calculate_mountain_hci

logger = logging.getLogger("pahadpath.weather_history")

# Repo-root-relative path
REPO_ROOT = Path(__file__).resolve().parents[3]
CSV_PATH = REPO_ROOT / "backend" / "app" / "data" / "uttarakhand_historical_weather.csv"

# Neutral fallbacks for HCI inputs when the CSV lacks those columns.
DEFAULT_CLOUD_COVER_PCT = 50.0
DEFAULT_WIND_SPEED_KMH = 10.0

# In-memory cache: destination_id -> {month: stats}
_CLIMATOLOGY_CACHE: dict[str, dict[int, dict[str, Any]]] | None = None


def _calculate_hci_for_month(
    avg_temp_max_c: float,
    avg_temp_min_c: float,
    avg_precipitation_mm: float,
    avg_cloud_cover_pct: float,
    avg_wind_speed_kmh: float,
) -> int:
    """Calculate HCI from monthly mean values."""
    temp_mean = (avg_temp_max_c + avg_temp_min_c) / 2.0
    return calculate_mountain_hci(
        temp_c=temp_mean,
        cloud_cover_pct=avg_cloud_cover_pct,
        rain_mm=avg_precipitation_mm,
        wind_kmh=avg_wind_speed_kmh,
    )


def _load_climatology() -> dict[str, dict[int, dict[str, Any]]]:
    """Load CSV and compute monthly stats per destination. Cached after first read."""
    global _CLIMATOLOGY_CACHE
    if _CLIMATOLOGY_CACHE is not None:
        return _CLIMATOLOGY_CACHE

    if not CSV_PATH.exists():
        logger.warning("Historical weather CSV not found at %s", CSV_PATH)
        _CLIMATOLOGY_CACHE = {}
        return _CLIMATOLOGY_CACHE

    # Accumulate per destination+month
    buckets: dict[str, dict[int, list[dict[str, float]]]] = {}

    with CSV_PATH.open("r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        fieldnames = set(reader.fieldnames or [])
        has_cloud = "cloud_cover_pct" in fieldnames
        has_wind = "wind_speed_kmh" in fieldnames

        for row in reader:
            dest_id = row["destination_id"]
            month = int(row["month"])
            precip = float(row["precipitation_mm"])
            rain = float(row["rain_mm"])
            snow = float(row["snowfall_cm"])
            tmax = float(row["temp_max_c"])
            tmin = float(row["temp_min_c"])
            cloud = (
                float(row["cloud_cover_pct"])
                if has_cloud and row.get("cloud_cover_pct") not in (None, "")
                else DEFAULT_CLOUD_COVER_PCT
            )
            wind = (
                float(row["wind_speed_kmh"])
                if has_wind and row.get("wind_speed_kmh") not in (None, "")
                else DEFAULT_WIND_SPEED_KMH
            )
            risk = int(row["high_landslide_risk"])

            buckets.setdefault(dest_id, {}).setdefault(month, []).append(
                {
                    "precip": precip,
                    "rain": rain,
                    "snow": snow,
                    "tmax": tmax,
                    "tmin": tmin,
                    "cloud": cloud,
                    "wind": wind,
                    "risk": risk,
                }
            )

    # Compute stats
    result: dict[str, dict[int, dict[str, Any]]] = {}
    for dest_id, months in buckets.items():
        result[dest_id] = {}
        for month, days in months.items():
            n = len(days)
            if n == 0:
                continue
            avg_precip = sum(d["precip"] for d in days) / n
            avg_rain = sum(d["rain"] for d in days) / n
            avg_snow = sum(d["snow"] for d in days) / n
            avg_tmax = sum(d["tmax"] for d in days) / n
            avg_tmin = sum(d["tmin"] for d in days) / n
            avg_cloud = sum(d["cloud"] for d in days) / n
            avg_wind = sum(d["wind"] for d in days) / n
            wet_days = sum(1 for d in days if d["precip"] >= 1.0)
            risk_days = sum(1 for d in days if d["risk"] == 1)
            wet_prob = wet_days / n
            risk_prob = risk_days / n

            # Friction: higher = worse travel conditions.
            # Weighted blend: 60% wet-day probability, 40% landslide-risk day probability.
            friction = round(100 * (0.6 * wet_prob + 0.4 * risk_prob))
            friction = max(0, min(100, friction))

            # Legacy friction-based tendency (kept for backward compatibility).
            tendency = round(90 - friction * 0.7)
            tendency = max(10, min(95, tendency))

            # Holiday Climate Index from monthly means — the primary weather signal.
            hci_score = _calculate_hci_for_month(
                avg_tmax, avg_tmin, avg_precip, avg_cloud, avg_wind
            )

            result[dest_id][month] = {
                "destination_id": dest_id,
                "month": month,
                "avg_precipitation_mm": round(avg_precip, 1),
                "avg_rain_mm": round(avg_rain, 1),
                "avg_snowfall_cm": round(avg_snow, 1),
                "avg_temp_max_c": round(avg_tmax, 1),
                "avg_temp_min_c": round(avg_tmin, 1),
                "avg_cloud_cover_pct": round(avg_cloud, 1),
                "avg_wind_speed_kmh": round(avg_wind, 1),
                "wet_day_probability": round(wet_prob, 3),
                "landslide_risk_probability": round(risk_prob, 3),
                "friction": friction,
                "visit_tendency": tendency,
                "hci_score": hci_score,
                "sample_days": n,
                "source": "Open-Meteo 5-year archive (2021-2026)",
                "note": (
                    f"Based on {n} daily records from the Open-Meteo historical archive "
                    f"for {dest_id} in month {month}. HCI {hci_score}/100; "
                    f"wet-day probability {wet_prob:.0%}; "
                    f"landslide-risk-day probability {risk_prob:.1%}."
                ),
            }

    _CLIMATOLOGY_CACHE = result
    logger.info("Loaded historical climatology with HCI for %d destinations", len(result))
    return result


def get_monthly_climatology(destination_name: str, month: int) -> dict[str, Any] | None:
    """Return climatology stats for a destination and month (1-12), or None if unknown."""
    climatology = _load_climatology()
    dest_key = destination_name.strip().casefold()
    if dest_key not in climatology:
        return None
    return climatology[dest_key].get(month)


def get_all_months_climatology(destination_name: str) -> list[dict[str, Any]] | None:
    """Return climatology for all 12 months for a destination, or None if unknown."""
    climatology = _load_climatology()
    dest_key = destination_name.strip().casefold()
    if dest_key not in climatology:
        return None
    months = climatology[dest_key]
    # Ensure all 1..12 present (some may have no data if node was incomplete)
    return [months.get(m) for m in range(1, 13) if m in months]


def get_historical_weather_friction(destination_name: str, month: int) -> dict[str, Any] | None:
    """Shorthand: return friction + tendency + HCI + note for a destination/month, or None."""
    clim = get_monthly_climatology(destination_name, month)
    if clim is None:
        return None
    return {
        "friction": clim["friction"],
        "visit_tendency": clim["visit_tendency"],
        "hci_score": clim["hci_score"],
        "avg_precipitation_mm": clim["avg_precipitation_mm"],
        "avg_temp_max_c": clim["avg_temp_max_c"],
        "avg_temp_min_c": clim["avg_temp_min_c"],
        "avg_cloud_cover_pct": clim["avg_cloud_cover_pct"],
        "avg_wind_speed_kmh": clim["avg_wind_speed_kmh"],
        "wet_day_probability": clim["wet_day_probability"],
        "landslide_risk_probability": clim["landslide_risk_probability"],
        "note": clim["note"],
        "source": clim["source"],
    }
